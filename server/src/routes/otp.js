import express from 'express'
import crypto from 'crypto'
import bcrypt from 'bcrypt'
import jwt from 'jsonwebtoken'
import { Resend } from 'resend'
import pool from '../config/db.js'
import customerAuth from '../middleware/customerAuth.js'

const router = express.Router()

// ===============================
// RESEND EMAIL
// ===============================

const resend = new Resend(
  process.env.RESEND_API_KEY
)

// ===============================
// OTP SETTINGS
// ===============================

const OTP_EXPIRY_MINUTES = 5
const MAX_OTP_ATTEMPTS = 5
const OTP_RESEND_COOLDOWN_SECONDS = 60

// ===============================
// 2FACTOR SETTINGS
// ===============================

const TWOFACTOR_API_KEY =
  process.env.TWOFACTOR_API_KEY

const TWOFACTOR_TEMPLATE =
  'JAYAS_KITCHEN_OTP'

// ===============================
// OTP COOLDOWN STORAGE
// ===============================

const otpCooldowns = new Map()

// Clean old cooldown entries
setInterval(() => {
  const expiry =
    OTP_RESEND_COOLDOWN_SECONDS * 1000

  const now = Date.now()

  for (
    const [key, timestamp]
    of otpCooldowns.entries()
  ) {
    if (now - timestamp >= expiry) {
      otpCooldowns.delete(key)
    }
  }
}, 60 * 1000)

// ===============================
// CREATE CUSTOMER JWT
// ===============================

const createCustomerToken = (customer) => {
  return jwt.sign(
    {
      customerId: customer.id,
      email: customer.email,
      phone: customer.phone,
    },
    process.env.JWT_SECRET,
    {
      expiresIn: '7d',
    }
  )
}

// ===============================
// GENERATE OTP
// ===============================
//
// Used for EMAIL OTP and
// MOBILE OTP.
//
// Mobile OTP is generated by
// our backend and then sent to
// 2Factor using manual generation.
//

const generateOtp = () => {
  return crypto
    .randomInt(100000, 1000000)
    .toString()
}

// ===============================
// HASH OTP
// ===============================

const hashOtp = async (otp) => {
  return bcrypt.hash(otp, 10)
}

// ===============================
// VALIDATE MOBILE
// ===============================

const isValidPhone = (phone) => {
  return /^[0-9]{10}$/.test(phone)
}

// ===============================
// VALIDATE EMAIL
// ===============================

const isValidEmail = (email) => {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(
    email
  )
}

