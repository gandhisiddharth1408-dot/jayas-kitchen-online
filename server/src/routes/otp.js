router.put(
  '/me',
  customerAuth,
  async (req, res) => {
    try {
      const customerId =
        req.customer?.customerId

      if (
        !customerId ||
        !Number.isInteger(
          Number(customerId)
        )
      ) {
        return res.status(401).json({
          success: false,
          message:
            'Invalid customer authentication.',
        })
      }

      const {
        name,
        phone,
        email,
      } = req.body

      const cleanName =
        typeof name === 'string'
          ? name.trim()
          : ''

      const cleanPhone =
        typeof phone === 'string'
          ? phone.trim()
          : ''

      const cleanEmail =
        typeof email === 'string'
          ? email.trim().toLowerCase()
          : ''

      if (!cleanName) {
        return res.status(400).json({
          success: false,
          message:
            'Full name is required.',
        })
      }

      if (cleanName.length > 100) {
        return res.status(400).json({
          success: false,
          message:
            'Full name must be 100 characters or less.',
        })
      }

      if (
        !cleanPhone ||
        !isValidPhone(cleanPhone)
      ) {
        return res.status(400).json({
          success: false,
          message:
            'Please enter a valid 10-digit mobile number.',
        })
      }

      if (
        cleanEmail &&
        !isValidEmail(cleanEmail)
      ) {
        return res.status(400).json({
          success: false,
          message:
            'Please enter a valid email address.',
        })
      }

      const phoneResult =
        await pool.query(
          `
          SELECT id
          FROM customers
          WHERE phone = $1
          AND id <> $2
          LIMIT 1
          `,
          [
            cleanPhone,
            Number(customerId),
          ]
        )

      if (
        phoneResult.rows.length > 0
      ) {
        return res.status(409).json({
          success: false,
          message:
            'This mobile number is already linked to another account.',
        })
      }

      if (cleanEmail) {
        const emailResult =
          await pool.query(
            `
            SELECT id
            FROM customers
            WHERE LOWER(email) = $1
            AND id <> $2
            LIMIT 1
            `,
            [
              cleanEmail,
              Number(customerId),
            ]
          )

        if (
          emailResult.rows.length > 0
        ) {
          return res.status(409).json({
            success: false,
            message:
              'This email address is already linked to another account.',
          })
        }
      }

      const result =
        await pool.query(
          `
          UPDATE customers
          SET
            name = $1,
            phone = $2,
            email = NULLIF($3, ''),
            updated_at = CURRENT_TIMESTAMP
          WHERE id = $4
          RETURNING
            id,
            name,
            phone,
            email,
            address,
            landmark,
            created_at,
            updated_at
          `,
          [
            cleanName,
            cleanPhone,
            cleanEmail,
            Number(customerId),
          ]
        )

      if (
        result.rows.length === 0
      ) {
        return res.status(404).json({
          success: false,
          message:
            'Customer account not found.',
        })
      }

      const customer =
        result.rows[0]

      const token =
        createCustomerToken(customer)

      return res.json({
        success: true,
        message:
          'Profile updated successfully.',
        token,
        customer,
      })
    } catch (error) {
      console.error(
        'Update customer profile failed:',
        error
      )

      return res.status(500).json({
        success: false,
        message:
          'Failed to update customer profile.',
      })
    }
  }
)

