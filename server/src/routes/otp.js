router.get(
  '/me',
  customerAuth,
  async (req, res) => {
    try {
      const customerId =
        req.customer?.customerId

      if (
        !customerId ||
        !Number.isInteger(
          Number(customerId)
        )
      ) {
        return res.status(401).json({
          success: false,
          message:
            'Invalid customer authentication.',
        })
      }

      const result =
        await pool.query(
          `
          SELECT
            id,
            name,
            phone,
            email,
            address,
            landmark,
            created_at,
            updated_at
          FROM customers
          WHERE id = $1
          LIMIT 1
          `,
          [Number(customerId)]
        )

      if (
        result.rows.length === 0
      ) {
        return res.status(404).json({
          success: false,
          message:
            'Customer account not found.',
        })
      }

      const customer =
        result.rows[0]

      return res.json({
        success: true,
        customer,
      })
    } catch (error) {
      console.error(
        'Fetch current customer failed:',
        error
      )

      return res.status(500).json({
        success: false,
        message:
          'Failed to fetch customer account.',
      })
    }
  }
)

